const { contextBridge, ipcRenderer } = require('electron');
const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
contextBridge.exposeInMainWorld('cardinal', {
  state: () => call('cl:state'),
  preferences: changes => call('cl:preferences', changes),
  start: () => call('cl:start'),
  restartApp: () => call('cl:restart-app'),
  stop: () => call('cl:stop'),
  restart: () => call('cl:restart'),
  cancelRestart: () => call('cl:cancel-restart'),
  setup: () => call('cl:setup'),
  plugins: () => call('cl:plugins'),
  reminderSettings: file => call('cl:reminder-settings', file),
  setReminderSetting: (file, key, value) => call('cl:set-reminder-setting', file, key, value),
  togglePlugin: (file, enabled) => call('cl:toggle-plugin', file, enabled),
  functions: () => call('cl:functions'),
  setFunction: (id, value) => call('cl:set-function', id, value),
  commands: () => call('cl:commands'),
  translate: texts => call('cl:translate', texts),
  accounts: () => call('cl:accounts'),
  addAccount: key => call('cl:add-account', key),
  switchAccount: id => call('cl:switch-account', id),
  removeAccount: id => call('cl:remove-account', id),
  saveCommands: list => call('cl:save-commands', list),
  profile: force => call('cl:profile', force),
  chats: () => call('cl:chats'),
  funpayView: () => call('cl:funpay-view'),
  chooseSound: () => call('cl:choose-sound'),
  testPopup: kind => call('cl:test-popup', kind),
  customSound: () => call('cl:custom-sound'),
  openUrl: url => call('cl:open-url', url),
  logs: () => call('cl:logs'),
  open: kind => call('cl:open', kind),
  choosePython: () => call('cl:choose-python'),
  chooseBotDir: () => call('cl:choose-bot-dir'),
  onEvent: callback => ipcRenderer.on('cl:event', (_event, value) => callback(value))
});
